export function createHash(algorithm) {
  if (String(algorithm).toLowerCase() !== 'sha256') throw new Error(`Digest method not supported: ${algorithm} (sha256 only)`);
  const parts = [], enc = new TextEncoder();
  const self = {
    update(data) { parts.push(typeof data === 'string' ? enc.encode(data) : new Uint8Array(data.buffer ?? data, data.byteOffset ?? 0, data.byteLength ?? data.length)); return self; },
    digest(encoding) { const all = Buffer.concat(parts), d = Buffer.from(sha256(all)); return encoding === 'hex' ? d.toString('hex') : d; },
  };
  return self;
}
