#!/usr/bin/env python3
"""Make theme/vga8x16.lua and theme/r3i6nos_vga8x16.h from the IBM VGA 8x16 font.

Development tool: run it only when the font changes, and commit the output. It needs Pillow
(with FreeType), which the image and CI do not. Usage: scripts/build_vga_font.py [--check]
(--check writes nothing and exits 1 if the committed files differ from what the font gives.)

The font is "WebPlus IBM VGA 8x16" from VileR's Ultimate Oldschool PC Font Pack
(https://int10h.org/oldschool-pc-fonts/), CC BY-SA 4.0: the licence and the original are in
theme/font/, and the two generated files are adaptations under the same licence.
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
WOFF = ROOT / "theme" / "font" / "WebPlus_IBM_VGA_8x16.woff"

# Code page 437 as the VGA draws it: 1-31 and 127 are pictures, not controls.
LOW = "\x00☺☻♥♦♣♠•◘○◙♂♀♪♫☼►◄↕‼¶§▬↨↑↓→←∟↔▲▼"
UNICODE = [ord(c) for c in LOW]
UNICODE += list(range(0x20, 0x7F)) + [0x2302]
UNICODE += [ord(bytes([b]).decode("cp437")) for b in range(0x80, 0x100)]
assert len(UNICODE) == 256


NOTICE = [
    'Font: "WebPlus IBM VGA 8x16" from The Ultimate Oldschool PC Font Pack v2.2, (c) 2016-2020 VileR,',
    'https://int10h.org/oldschool-pc-fonts/ , licensed under CC BY-SA 4.0 (https://creativecommons.org/licenses/by-sa/4.0/).',
    "CHANGES: the font's 256 code page 437 characters were rasterised at 16 px to 1-bit 8x16 bitmaps by scripts/build_vga_font.py",
    "(r3i6nos, 2026); this file is that adaptation and is licensed under CC BY-SA 4.0, NOT under the repository's MIT licence.",
    'The font is provided as is, without warranties (see theme/font/LICENSE.TXT, section 5).',
]


def glyph(font, cp):
    """16 bytes, one a row, the top bit the leftmost pixel."""
    if cp in (0, 0x20, 0xA0):
        return bytes(16)
    im = Image.new("1", (8, 16), 0)
    d = ImageDraw.Draw(im)
    d.fontmode = "1"
    d.text((0, 0), chr(cp), font=font, fill=1)
    rows = []
    for y in range(16):
        v = 0
        for x in range(8):
            v = v << 1 | (1 if im.getpixel((x, y)) else 0)
        rows.append(v)
    return bytes(rows)


def main():
    font = ImageFont.truetype(str(WOFF), 16)
    glyphs = [glyph(font, cp) for cp in UNICODE]
    blank = [i for i, g in enumerate(glyphs) if not any(g) and i not in (0, 32, 255)]
    if blank:
        sys.exit(f"build_vga_font: the font has no picture for code page 437 characters {blank}")

    lua = [
        "-- GENERATED by scripts/build_vga_font.py: do not edit.",
        *[f"-- {line}" for line in NOTICE],
        "-- glyphs[i + 1]: 32 hex digits, 16 rows of 8 pixels, for code page 437 character i (0 to 255).",
        "-- unicode[i + 1]: the Unicode code point that character stands for.",
        "return {",
        "  glyphs = {",
    ]
    lua += [f'    "{g.hex()}",' for g in glyphs]
    lua += ["  },", "  unicode = {"]
    for i in range(0, 256, 8):
        lua.append("    " + ", ".join(str(c) for c in UNICODE[i:i + 8]) + ",")
    lua += ["  },", "}", ""]
    outputs = {ROOT / "theme" / "vga8x16.lua": "\n".join(lua)}

    h = [
        "/* GENERATED by scripts/build_vga_font.py: do not edit.",
        *[" * " + line for line in NOTICE],
        " * r3i6nos_vga8x16[i][row]: the top bit is the leftmost pixel. r3i6nos_cp437[i]: the Unicode code point. */",
        "#ifndef R3I6NOS_VGA8X16_H",
        "#define R3I6NOS_VGA8X16_H",
        "static const unsigned char r3i6nos_vga8x16[256][16] = {",
    ]
    h += ["  {" + ",".join(f"0x{b:02x}" for b in g) + "}," for g in glyphs]
    h += ["};", "static const unsigned short r3i6nos_cp437[256] = {"]
    for i in range(0, 256, 8):
        h.append("  " + ",".join(f"0x{c:04x}" for c in UNICODE[i:i + 8]) + ",")
    h += ["};", "#endif", ""]
    outputs[ROOT / "theme" / "r3i6nos_vga8x16.h"] = "\n".join(h)
    if "--check" in sys.argv:
        stale = [p.name for p, text in outputs.items() if not p.exists() or p.read_text() != text]
        if stale:
            sys.exit(f"build_vga_font: out of date: {', '.join(stale)} (run scripts/build_vga_font.py)")
        print("build_vga_font: up to date")
        return
    for p, text in outputs.items():
        p.write_text(text)
    print("wrote theme/vga8x16.lua and theme/r3i6nos_vga8x16.h")


main()
