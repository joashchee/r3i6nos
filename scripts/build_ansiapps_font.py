#!/usr/bin/env python3
"""Import ANSIapps Mono (the official ansiapps font, 10 x 20 size) into the theme: theme/font/ansiapps-mono/ and the code page 437 tables.

The font is made in its own repository (~/Coding/ansiapps-mono-font, or $ANSIAPPS_MONO_DIR; clean-room, SIL OFL 1.1). This script reads what that
repository builds (`node tools/build.mjs`, `node tools/build10x20.mjs`) and writes, with the standard library only:

  theme/font/ansiapps-mono/ansiapps_mono10x20.h      the 10x20 bitmaps for C (the upstream header, unchanged: r3mono_glyph, r3mono_find ...)
  theme/font/ansiapps-mono/ansiapps_mono10x20.lua    the same for Lua (glyphs[i] 60 hex digits, cmap[code point] = i, 1-based)
  theme/font/ansiapps-mono/ansiapps-mono.json        the same for web canvases and the screen mirror's page (+ every name)
  theme/font/ansiapps-mono/AnsiappsMono10x20-Regular.bdf   the bitmap font (Pyxel, X11)
  theme/font/ansiapps-mono/ansiapps_mono_names.h|.lua, glyph-names.json   every named glyph, with its size (cells wide and tall)
  theme/font/ansiapps-mono/ansiapps_cp437.h|.lua     code page 437 on the font: byte -> code point, the 8x16 and 10x20 bitmaps by byte
  theme/font/ansiapps-mono/ansiapps_portrait.h|.lua  the portrait maker's parts, slot kinds, layouts and join tables (docs/PORTRAIT-PARTS.md upstream)
  theme/font/ansiapps-mono/OFL.txt, README.txt, glyph-coverage-report.txt

Usage: scripts/build_ansiapps_font.py [--check]   (--check writes nothing and exits 1 when a committed file differs.)
"""
import json
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = Path(os.environ.get("ANSIAPPS_MONO_DIR") or ROOT.parent / "ansiapps-mono-font")
OUT = ROOT / "theme" / "font" / "ansiapps-mono"
CW, CH = 10, 20


def need(path):
    p = SRC / path
    if not p.exists():
        raise SystemExit(f"build_ansiapps_font: {p} is missing (build the font there first: node tools/build.mjs && node tools/build10x20.mjs)")
    return p


def load_json(path):
    return json.loads(need(path).read_text())


def c_macro(name):
    return "R3I_" + "".join(c.upper() if c.isalnum() else "_" for c in name)


def utf8_oct(cp):
    return "".join(f"\\{b:03o}" for b in chr(cp).encode("utf-8"))


def utf8_dec(cp):
    return "".join("\\%03d" % b for b in chr(cp).encode("utf-8"))


HEAD = ("ANSIapps Mono, the official font of the ansiapps family and r3i6nos (10x20 size). GENERATED by scripts/build_ansiapps_font.py from the font's own\n"
        "repository (ansiapps-mono-font): do not edit. Licence: SIL OFL 1.1, Reserved Font Name \"ANSIapps Mono\" (theme/font/ansiapps-mono/OFL.txt).")


def glyph_table(d10):
    """(store, cmap): unique 10x20 bitmaps (60 hex digits each) in first-seen order, and code point -> index (0-based)."""
    store, index, cmap = [], {}, {}
    for g in d10["glyphs"]:
        if len(g["rows"]) != 60:
            raise SystemExit(f"U+{g['cp']:04X} is not 10x20")
        i = index.get(g["rows"])
        if i is None:
            i = index[g["rows"]] = len(store)
            store.append(g["rows"])
        cmap[g["cp"]] = i
    return store, cmap


def names_from(d10, reg, own):
    """name -> {cp, cols, rows}: every named glyph of Plane 15 and 16 (a name is its first cell; `.cellN` and `.rowN` are the rest of it)."""
    by_cp = {g["cp"]: g for g in d10["glyphs"]}
    first = {}
    for g in d10["glyphs"]:
        n = g["name"]
        if g["cp"] >= 0xF0000 and not re.search(r"\.(cell\d+|row\d+)$", n) and not re.search(r"\.row\d+\.cell\d+$", n):
            if n in first:
                raise SystemExit(f"two glyphs are named {n}")
            first[n] = g["cp"]
    for table in (reg, own):
        for n, cp in table.items():
            if first.get(n) != cp:
                raise SystemExit(f"the name file says {n} is U+{cp:X}, the font has {first.get(n)}")
    out = {}
    for n, cp in first.items():
        cols = 1
        while f"{n}.cell{cols + 1}" in {by_cp.get(cp + cols, {}).get("name")}:
            cols += 1
        rows = 1
        while by_cp.get(cp + rows * cols, {}).get("name") == f"{n}.row{rows + 1}":
            rows += 1
        out[n] = {"cp": cp, "cols": cols, "rows": rows}
    seen = {}
    for n in out:
        m = c_macro(n)
        if m in seen:
            raise SystemExit(f"{n} and {seen[m]} make the same C name {m}")
        seen[m] = n
    return out


def cell_cps(e, row):
    return [e["cp"] + row * e["cols"] + c for c in range(e["cols"])]


def c_header(d10_header):
    return d10_header


def lua_table(store, cmap):
    cps = sorted(cmap)
    L = ["-- " + HEAD.replace("\n", "\n-- "),
         "-- glyphs[i]: 20 rows of 3 hex digits (10 bits, the top bit the leftmost pixel), row 0 the top. cmap[code point] = i (1-based).",
         "-- Capitals are rows 3-14 (0-based), the baseline is below row 14.", "return {", f"  width = {CW}, height = {CH}, base = 15,", "  glyphs = {"]
    L += [f'    "{h}",' for h in store]
    L += ["  },", "  cmap = {"]
    for i in range(0, len(cps), 6):
        L.append("    " + " ".join(f"[{c}]={cmap[c] + 1}," for c in cps[i:i + 6]))
    L += ["  },", "}", ""]
    return "\n".join(L)


def json_table(store, cmap, names):
    d = {"family": "ANSIapps Mono", "width": CW, "height": CH, "base": 15, "glyphs": store,
         "cmap": {str(c): cmap[c] for c in sorted(cmap)},
         "names": {n: names[n] for n in sorted(names)}}
    return json.dumps(d, separators=(",", ":")) + "\n"


def names_h(names):
    L = ["/* " + HEAD.replace("\n", "\n * ") + "\n * One UTF-8 string a name (octal escapes, so a following digit cannot join them): the cells of its first row, left to right."
         "\n * A glyph more than one cell tall has its next rows under <name>.row2, <name>.row3 (print each on the row below). r3mono_shape(name) says how many cells"
         "\n * wide and tall a glyph is. R3I_<NAME> macros for names known when you write the code, r3mono_name(\"pad.btn.A.on\") for names built at run time. */",
         "#ifndef R3I6NOS_MONO_NAMES_H", "#define R3I6NOS_MONO_NAMES_H", "#include <string.h>"]
    rows = []
    for n in sorted(names):
        e = names[n]
        for r in range(e["rows"]):
            nm = n if r == 0 else f"{n}.row{r + 1}"
            rows.append((nm, e, r))
    rows.sort(key=lambda t: t[0].encode())
    for nm, e, r in rows:
        L.append(f'#define {c_macro(nm)} "' + "".join(utf8_oct(c) for c in cell_cps(e, r)) + '"')
    L += ["typedef struct { const char *name, *utf8; unsigned int cp; unsigned char cols, rows; } R3MonoName;",
          "/* name, the cells of that row, the code point of its first cell, cells wide, cells tall (of the whole glyph) */",
          "static const R3MonoName r3mono_names[] = {"]
    for nm, e, r in rows:
        L.append(f'    {{"{nm}", {c_macro(nm)}, 0x{e["cp"] + r * e["cols"]:X}u, {e["cols"]}, {e["rows"]}}},')
    L += ["};", "#define R3MONO_NAMES ((int)(sizeof r3mono_names / sizeof r3mono_names[0]))",
          "/* The entry of a glyph name (sorted table, binary search), or NULL. */",
          "static inline const R3MonoName *r3mono_entry(const char *name) {",
          "    int lo = 0, hi = R3MONO_NAMES - 1;",
          "    while (lo <= hi) {", "        int mid = (lo + hi) / 2, c = strcmp(name, r3mono_names[mid].name);",
          "        if (c == 0) return &r3mono_names[mid];", "        if (c < 0) hi = mid - 1; else lo = mid + 1;", "    }",
          "    return 0;", "}",
          "/* The string for a glyph name, or NULL. */",
          "static inline const char *r3mono_name(const char *name) { const R3MonoName *e = r3mono_entry(name); return e ? e->utf8 : 0; }",
          "#endif", ""]
    return "\n".join(L)


def names_lua(names):
    L = ["-- " + HEAD.replace("\n", "\n-- "),
         "-- names[name] = the UTF-8 string to print (the cells of its first row); a glyph more than one cell tall has its next rows under name.row2, name.row3.",
         "-- shapes[name] = { cp, cols, rows }.", "local names, shapes = {}, {}"]
    for n in sorted(names):
        e = names[n]
        for r in range(e["rows"]):
            nm = n if r == 0 else f"{n}.row{r + 1}"
            L.append(f'names["{nm}"] = "' + "".join(utf8_dec(c) for c in cell_cps(e, r)) + '"')
        L.append(f'shapes["{n}"] = {{ {e["cp"]}, {e["cols"]}, {e["rows"]} }}')
    L += ["names.shapes = shapes", "return names", ""]
    return "\n".join(L)


def cp437_tables():
    cp437, pic = load_json("data/cp437.json"), load_json("data/cp437-pictures.json")
    uni = []
    for b in range(256):
        h = f"{b:02X}"
        uni.append(int(pic[h], 16) if h in pic else int(cp437[h], 16))
    return uni


def cp437_files(uni, d8, d10, store, cmap):
    rows8 = {g["cp"]: g["rows"] for g in d8["glyphs"]}
    rows10 = {g["cp"]: g["rows"] for g in d10["glyphs"]}
    blank8, blank10 = "0" * 32, "0" * 60
    g8, g10, miss = [], [], []
    for b in range(256):
        cp = uni[b] if b else 0x20
        if cp not in rows8 or cp not in rows10:
            miss.append(b)
            continue
        g8.append(rows8[cp])
        g10.append(rows10[cp])
    if miss:
        raise SystemExit(f"code page 437 bytes with no glyph in the font: {miss}")
    g8[0], g10[0] = blank8, blank10                       # byte 0 is blank
    # FNV-1a over every pixel of every code page 437 glyph in the order byte, row, column (the theme's glyph hash, in C and Lua)
    h = 2166136261
    for b in range(256):
        for r in range(CH):
            v = int(g10[b][r * 3:r * 3 + 3], 16)
            for x in range(CW):
                h ^= (v >> (CW - 1 - x)) & 1
                h = (h * 16777619) & 0xFFFFFFFF
    H = ["/* " + HEAD.replace("\n", "\n * "),
         " * Code page 437 on ANSIapps Mono. r3i6nos_cp437[b]: the Unicode code point byte b stands for (the pictures for 1-31 and 127; byte 0 is blank).",
         " * ansiapps8x16[b][row]: the 8x16 bitmap (top bit the leftmost pixel) for tools that draw 8x16 (ANSI art). ansiapps_cp437_10x20[b][row]: the 10x20 one",
         " * (10 bits, bit 9 the leftmost pixel), what the theme draws. */",
         "#ifndef ANSIAPPS_CP437_H", "#define ANSIAPPS_CP437_H",
         f"#define R3_GLYPH_HASH 0x{h:08x}u /* FNV-1a of every pixel of ansiapps_cp437_10x20, in the order byte, row, column; theme.glyphHash() in Lua gives the same */",
         "static const unsigned short r3i6nos_cp437[256] = {"]
    H += ["    " + ",".join(f"0x{uni[i + j]:04X}" for j in range(8)) + "," for i in range(0, 256, 8)]
    H += ["};", "static const unsigned char ansiapps8x16[256][16] = {"]
    H += ["    {" + ",".join("0x" + g[i:i + 2] for i in range(0, 32, 2)) + "}," for g in g8]
    H += ["};", "static const unsigned short ansiapps_cp437_10x20[256][20] = {"]
    H += ["    {" + ",".join("0x" + g[i:i + 3] for i in range(0, 60, 3)) + "}," for g in g10]
    H += ["};", "#endif", ""]
    L = ["-- " + HEAD.replace("\n", "\n-- "),
         "-- Code page 437 on ANSIapps Mono. unicode[i + 1]: the code point byte i stands for. glyphs[i + 1]: 32 hex digits, 16 rows of 8 pixels (8x16).",
         "-- glyphs10[i + 1]: 60 hex digits, 20 rows of 10 pixels (10x20, what the theme draws). Byte 0 is blank.", f"-- hash = 0x{h:08x}", "return {",
         "  unicode = {"]
    L += ["    " + ", ".join(str(uni[i + j]) for j in range(8)) + "," for i in range(0, 256, 8)]
    L += ["  },", "  glyphs = {"] + [f'    "{g}",' for g in g8] + ["  },", "  glyphs10 = {"] + [f'    "{g}",' for g in g10] + ["  },", f"  hash = 0x{h:08x},", "}", ""]
    return "\n".join(H), "\n".join(L)


def kind_model(S, kind):
    """The colour model of a slot kind (upstream tools/lib/portrait.mjs modelOf): the family's, or its tier's when the tiers differ."""
    family, *rest = kind.split(".")
    f = S["families"][family]
    tier = rest[-1] if rest else None
    m = (f.get("tierModel") or {}).get(tier) or f["model"]
    return {"silhouette": "s", "line": "l", "hair": "h"}[m]


def portrait_files(pj, cmap):
    S = pj
    fams = list(S["families"])
    in_layouts = {k for g in S["layouts"].values() for row in g for c in row for k in (c if isinstance(c, list) else [c])}
    kinds = sorted({p["kind"] for p in S["parts"]} | in_layouts)
    kind_ix = {k: i for i, k in enumerate(kinds)}
    parts = S["parts"]
    part_ix = {p["name"]: i for i, p in enumerate(parts)}
    for p in parts:
        if p["codePoint"] not in cmap:
            raise SystemExit(f"portrait part {p['name']} has no glyph")
    pairs = []                    # (a, b, dir): a is left of or above b, from the sides 'right' and 'bottom'
    for p in parts:
        for side, m in p.get("joins", {}).items():
            if side in ("right", "bottom"):
                for lst in m.values():
                    for o in lst:
                        pairs.append((part_ix[p["name"]], part_ix[o], "h" if side == "right" else "v"))
    pairs.sort()
    layouts = []
    for lname in sorted(S["layouts"]):
        g = S["layouts"][lname]
        layouts.append((lname, [[[kind_ix[k] for k in (c if isinstance(c, list) else [c])] for c in row] for row in g]))
    comp = [(c["a"], c["b"], c["dir"], c["partsA"], c["partsB"], c["compatible"], c["compared"]) for c in S["compatibility"] if c["a"] in kind_ix and c["b"] in kind_ix]
    fam_info = {}
    for f, v in S["families"].items():
        fam_info[f] = (int(bool(v.get("mirrored"))), int(v.get("edgeStep", 0)), int(bool(v.get("taper"))), v.get("model", ""),
                       (v.get("overhang") or {}).get("max", -1), list((v.get("overhang") or {}).get("over", [])))
    H = ["/* " + HEAD.replace("\n", "\n * "),
         " * The portrait maker's parts (upstream docs/PORTRAIT-PARTS.md): a portrait is 8 x 4 cells; each cell holds one part of a slot kind. ap_part: name, code point,",
         " * kind, family, alias (a name for another part's picture). ap_join: part a may sit left of (h) or above (v) part b. ap_layout[layout][row][col]: the kinds a",
         " * cell may hold (up to 2). ap_compat: the upstream matrix of how many pairs of two neighbouring kinds join (measured on the 8x16 bitmaps). */",
         "#ifndef ANSIAPPS_PORTRAIT_H", "#define ANSIAPPS_PORTRAIT_H",
         f"#define AP_PARTS {len(parts)}", f"#define AP_KINDS {len(kinds)}", f"#define AP_FAMILIES {len(fams)}", f"#define AP_JOINS {len(pairs)}",
         f"#define AP_LAYOUTS {len(layouts)}", f"#define AP_COMPAT {len(comp)}",
         f"#define AP_KINK_MAX {int(S['kink']['maxSlopeChange'])}",
         "static const char *const ap_kind[AP_KINDS] = {" + ",".join(f'"{k}"' for k in kinds) + "};",
         "static const char *const ap_layout_name[AP_LAYOUTS] = {" + ",".join(f'"{n}"' for n, _ in layouts) + "};",
         "/* how each kind is coloured: 's' a silhouette (ink skin or cloth on the backdrop), 'l' a line (ink on skin), 'h' hair (ink hair on the backdrop) */",
         "static const char ap_kind_model[AP_KINDS] = {" + ",".join("'" + kind_model(S, k) + "'" for k in kinds) + "};",
         "/* name, mirrored (the .R part is the .L part reversed), edge step (8x16 pixels), taper, overhang max (8x16 pixels, -1 none), the families the overhang is over (bit = family) */",
         "typedef struct { const char *name; unsigned char mirrored, step, taper; signed char overhang; unsigned short over; } ApFamily;",
         "static const ApFamily ap_family[AP_FAMILIES] = {"]
    H += [f'    {{"{f}", {fam_info[f][0]}, {fam_info[f][1]}, {fam_info[f][2]}, {fam_info[f][4]}, 0x{sum(1 << fams.index(o) for o in fam_info[f][5]):X}}},' for f in fams]
    H += ["};", "typedef struct { const char *name; unsigned int cp; unsigned short kind; unsigned char family, alias; } ApPart;", "static const ApPart ap_part[AP_PARTS] = {"]
    H += [f'    {{"{p["name"]}", 0x{p["codePoint"]:X}u, {kind_ix[p["kind"]]}, {fams.index(p["family"])}, {int(bool(p.get("alias")))}}},' for p in parts]
    H += ["};", "typedef struct { unsigned short a, b; char dir; } ApJoin;", "static const ApJoin ap_join[AP_JOINS] = {"]
    H += [f"    {{{a},{b},'{d}'}}," for a, b, d in pairs]
    H += ["};", "/* the kinds each cell may hold: kinds[0], kinds[1] (-1 none) */",
          "static const signed char ap_cells[AP_LAYOUTS][4][8][2] = {"]
    for _, g in layouts:
        H.append("    {")
        for row in g:
            H.append("        {" + ",".join("{" + ",".join(str(k) for k in (c + [-1] * (2 - len(c)))) + "}" for c in row) + "},")
        H.append("    },")
    H += ["};", "typedef struct { unsigned short a, b; char dir; unsigned short parts_a, parts_b, compatible; unsigned char compared; } ApCompat;",
          "static const ApCompat ap_compat[AP_COMPAT] = {"]
    H += [f"    {{{kind_ix[a]},{kind_ix[b]},'{d}',{pa},{pb},{c},{int(bool(cmpd))}}}," for a, b, d, pa, pb, c, cmpd in comp]
    H += ["};", "#endif", ""]
    L = ["-- " + HEAD.replace("\n", "\n-- "), "-- The portrait maker's parts (see ansiapps_portrait.h). Counts only; the C header has the tables.",
         f"return {{ parts = {len(parts)}, kinds = {len(kinds)}, joins = {len(pairs)}, layouts = {len(layouts)} }}", ""]
    return "\n".join(H), "\n".join(L)


def coverage(d10, names, store, cmap, d8):
    cps = set(cmap)
    L = ["ANSIapps Mono 10x20: glyph coverage (GENERATED by scripts/build_ansiapps_font.py)", "=" * 70, "",
         f"code points: {len(cps)}   distinct bitmaps: {len(store)}   named glyphs: {len(names)}",
         f"8x16 glyphs upstream: {len(d8['glyphs'])}"]

    def rng(a, z, label):
        L.append(f"{label} U+{a:04X}-{z:04X}: {len([c for c in range(a, z + 1) if c in cps])}/{z - a + 1}")
    rng(0x20, 0x7E, "ASCII"); rng(0xA0, 0xFF, "Latin-1"); rng(0x100, 0x17F, "Latin Extended-A"); rng(0x2500, 0x257F, "Box drawing")
    rng(0x2580, 0x259F, "Blocks"); rng(0x2800, 0x28FF, "Braille"); rng(0x1FB00, 0x1FB3B, "Sextants"); rng(0x1CD00, 0x1CDE5, "Octants"); rng(0xE0A0, 0xE0BF, "Powerline")
    L += ["", "Plane 15 and 16 (private use):",
          f"  portrait parts U+F0A00-F12FF: {len([c for c in cps if 0xF0A00 <= c <= 0xF12FF])}",
          f"  game glyphs U+F0000-F09FF and F0900-F09D7: {len([c for c in cps if 0xF0000 <= c <= 0xF09FF])}",
          f"  registry U+10F000-10FFFF: {len([c for c in cps if 0x10F000 <= c <= 0x10FFFF])}", "",
          "Named glyphs by size (cells wide x tall):"]
    cnt = {}
    for e in names.values():
        cnt[(e["cols"], e["rows"])] = cnt.get((e["cols"], e["rows"]), 0) + 1
    L += [f"  {c}x{r}: {n}" for (c, r), n in sorted(cnt.items())]
    L += ["  wide counterparts (.wide): " + str(len([n for n in names if n.endswith(".wide")])),
          "  tall counterparts (.tall): " + str(len([n for n in names if n.endswith(".tall")])), ""]
    return "\n".join(L)


