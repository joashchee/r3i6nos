def build():
    d10 = load_json("fonts/10x20/ansiapps-mono10x20.json")
    d8 = load_json("fonts/ansiapps-mono.json")
    reg, own = load_json("data/registry-names.json"), load_json("data/ansiapps-names.json")
    pj = load_json("fonts/portrait-glyphs.json")
    store, cmap = glyph_table(d10)
    names = names_from(d10, reg, own)
    uni = cp437_tables()
    cp437_h, cp437_lua = cp437_files(uni, d8, d10, store, cmap)
    por_h, por_lua = portrait_files(pj, cmap)
    header = need("fonts/10x20/ansiapps_mono10x20.h").read_text()
    out = {
        "ansiapps_mono10x20.h": header,
        "ansiapps_mono10x20.lua": lua_table(store, cmap),
        "ansiapps-mono.json": json_table(store, cmap, names),
        "AnsiappsMono10x20-Regular.bdf": need("fonts/10x20/AnsiappsMono10x20-Regular.bdf").read_text(),
        "ansiapps_mono_names.h": names_h(names),
        "ansiapps_mono_names.lua": names_lua(names),
        "glyph-names.json": json.dumps({n: names[n]["cp"] for n in sorted(names)}, indent=1) + "\n",
        "ansiapps_cp437.h": cp437_h,
        "ansiapps_cp437.lua": cp437_lua,
        "ansiapps_portrait.h": por_h,
        "ansiapps_portrait.lua": por_lua,
        "glyph-coverage-report.txt": coverage(d10, names, store, cmap, d8),
        "OFL.txt": need("OFL.txt").read_text(),
        "README.txt": README,
    }
    return out


def main(argv):
    out = build()
    if "--check" in argv:
        stale = [n for n, t in out.items() if not (OUT / n).exists() or (OUT / n).read_text() != t]
        if stale:
            print(f"build_ansiapps_font: out of date: {', '.join(stale)} (run scripts/build_ansiapps_font.py)", file=sys.stderr)
            return 1
        print("build_ansiapps_font: up to date")
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for n, t in out.items():
        (OUT / n).write_text(t)
    print(f"wrote {len(out)} files in {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
