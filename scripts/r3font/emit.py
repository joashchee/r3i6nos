def coverage(R, miss):
    L = ["R3i6nos Mono: glyph coverage report (GENERATED by scripts/build_r3_font.py)", "=" * 70, ""]
    cps = set(R.all_cps())
    tot = len(cps)
    L.append(f"code points: {tot}   drawn glyphs: {len(R.g)}   aliases (same picture): {len(R.alias)}")
    L.append("")
    # CP437: every byte -> the picture the VGA draws (the glyph row of the theme's table)
    from .base import cp437
    _, uni = cp437()
    bad = [i for i in range(256) if uni[i] not in cps]
    L.append(f"CP437: {256 - len(bad)}/256 bytes have a glyph at their Unicode code point; missing: {bad or 'none'}")
    ctl = [i for i in range(256) if 0xF000 + i not in cps]
    L.append(f"raw CP437 (U+F000 + byte): {256 - len(ctl)}/256")

    def rng(a, z, label):
        have = [c for c in range(a, z + 1) if c in cps]
        L.append(f"{label} U+{a:04X}-{z:04X}: {len(have)}/{z - a + 1}")
    rng(0x2500, 0x257F, "Box drawing"); rng(0x2580, 0x259F, "Block elements"); rng(0x2800, 0x28FF, "Braille")
    rng(0x25A0, 0x25FF, "Geometric shapes"); rng(0x2190, 0x21FF, "Arrows"); rng(0x2460, 0x2473, "Circled digits")
    rng(0x1FB00, 0x1FB3B, "Sextants"); rng(0xA0, 0xFF, "Latin-1 Supplement"); rng(0x100, 0x17F, "Latin Extended-A")
    rng(0x2400, 0x2421, "Control pictures"); rng(0x23E9, 0x23FA, "Media controls (partial block)"); rng(0xE0A0, 0xE0BF, "Powerline")
    L.append("")
    L.append("Still missing in Latin-1 and Latin Extended-A (to be drawn by hand): " + " ".join(f"U+{c:04X}" for c in miss if c not in cps))
    L.append("")
    L.append("Code points by section:")
    sec = {}
    for c in cps:
        sec.setdefault(R.where.get(R.alias.get(c, c), R.where.get(c, "alias")), []).append(c)
    for s, cs in sorted(sec.items(), key=lambda kv: min(kv[1])):
        L.append(f"  {len(cs):5d}  {s}")
    L.append("")
    L.append("Private use (Plane 16) blocks, used / size:")
    from .registry import BLOCKS
    for b, (a, z, what) in BLOCKS.items():
        used = len([c for c in cps if a <= c <= z])
        L.append(f"  U+{a:X}-{z:X}  {used:4d}/{z - a + 1:4d}  {b}: {what}")
    L.append("")
    names = len(R.names)
    L.append(f"named glyphs: {names}")
    return "\n".join(L) + "\n"
