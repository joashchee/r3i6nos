"""Write every non-TrueType output from a built Registry. Deterministic (no dates), so `build_r3_font.py --check` can compare.

The glyph store is shared: identical bitmaps are stored once, and `cmap` maps a code point to the glyph index. Outputs, all in
theme/font/r3i6nos-mono/: .bdf (Pyxel, X11, many tools), BMFont .fnt + atlas .png (LOVE 11/12, Godot, Defold), r3i6nos_mono10x20.h
(C and SDL2), r3i6nos_mono10x20.lua (LOVE bitmap path), r3i6nos-mono.json (web canvases, the screen mirror), name tables for C, Lua and
CSS, the coverage report. TTF/WOFF/WOFF2 come from ttf.py (fontTools, in Docker).
"""
import json
import struct
import unicodedata
import zlib

from .canvas import CW, CH, ASCENT, DESCENT

FAMILY = "R3i6nos Mono"


def glyph_store(R):
    """(list of hex strings, {cp: index}), the glyphs in first-use order of the sorted code points."""
    store, index, cmap = [], {}, {}
    for cp in R.all_cps():
        g = R.glyph(cp)
        h = g.hex()
        if h not in index:
            index[h] = len(store)
            store.append(h)
        cmap[cp] = index[h]
    return store, cmap


def utf8_oct(cp):
    return "".join(f"\\{b:03o}" for b in chr(cp).encode("utf-8"))


def c_name(name):
    return "R3I_" + "".join(c.upper() if c.isalnum() else "_" for c in name)


def rows_of(h):
    d = 4
    return [int(h[i:i + d], 16) for i in range(0, len(h), d)]


def bdf(R):
    out = ["STARTFONT 2.1", f"FONT -r3i6nos-{FAMILY.replace(' ', '')}-medium-r-normal--{CH}-{CH * 10}-75-75-c-{CW * 10}-iso10646-1",
           f"SIZE {CH} 75 75", f"FONTBOUNDINGBOX {CW} {CH} 0 -{DESCENT}", "STARTPROPERTIES 8", "FONT_ASCENT %d" % ASCENT,
           "FONT_DESCENT %d" % DESCENT, "DEFAULT_CHAR 63", 'FAMILY_NAME "%s"' % FAMILY, 'WEIGHT_NAME "Medium"', 'SPACING "C"',
           'COPYRIGHT "CC BY-SA 4.0, see theme/font/r3i6nos-mono/README.txt"', 'CHARSET_REGISTRY "ISO10646"', "ENDPROPERTIES",
           f"CHARS {len(R.all_cps())}"]
    for cp in R.all_cps():
        out += [f"STARTCHAR u{cp:04X}", f"ENCODING {cp}", "SWIDTH 500 0", f"DWIDTH {CW} 0", f"BBX {CW} {CH} 0 -{DESCENT}", "BITMAP"]
        out += [f"{r << 6:04X}" for r in R.glyph(cp).rows_int()]
        out.append("ENDCHAR")
    out.append("ENDFONT")
    return "\n".join(out) + "\n"


def png_rgba(path, w, h, alpha_rows):
    raw = b"".join(b"\x00" + b"".join(b"\xff\xff\xff" + bytes([255 if v else 0]) for v in r) for r in alpha_rows)

    def chunk(t, d):
        c = struct.pack(">I", len(d)) + t + d
        return c + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)
    data = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0))
    data += chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")
    path.write_bytes(data)


def bmfont(R, fnt_path, png_path):
    cps = R.all_cps()
    cols = 64
    cw, ch = CW + 1, CH + 1
    rws = (len(cps) + cols - 1) // cols
    W, H = cols * cw, rws * ch
    img = [[0] * W for _ in range(H)]
    lines = [f'info face="{FAMILY}" size={CH} bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=1,1 outline=0',
             f"common lineHeight={CH} base={ASCENT} scaleW={W} scaleH={H} pages=1 packed=0", f'page id=0 file="{png_path.name}"',
             f"chars count={len(cps)}"]
    for i, cp in enumerate(cps):
        x, y = (i % cols) * cw, (i // cols) * ch
        g = R.glyph(cp)
        for j in range(CH):
            for k in range(CW):
                img[y + j][x + k] = g.p[j][k]
        lines.append(f"char id={cp} x={x} y={y} width={CW} height={CH} xoffset=0 yoffset=0 xadvance={CW} page=0 chnl=15")
    png_rgba(png_path, W, H, img)
    fnt_path.write_text("\n".join(lines) + "\n")


HEAD = ("R3i6nos Mono, the 10x20 text-mode font of r3i6nos and the ansiapps apps. GENERATED by scripts/build_r3_font.py: do not edit.\n"
        "Licence: CC BY-SA 4.0 (the CP437 letters are VileR's 'WebPlus IBM VGA 8x16', mapped to 10x20; see theme/font/r3i6nos-mono/README.txt).")


def c_header(R, store, cmap):
    cps = sorted(cmap)
    L = ["/* " + HEAD.replace("\n", "\n * ") + "\n * r3mono_glyph[g][row]: 10 bits, bit 9 the leftmost pixel; row 0 the top. r3mono_cp / r3mono_idx: sorted code points -> glyph.\n"
         " * Look a code point up with r3mono_find(). Row 15 is the first below the baseline (capitals are rows 3-14). */",
         "#ifndef R3I6NOS_MONO10X20_H", "#define R3I6NOS_MONO10X20_H",
         f"#define R3MONO_W {CW}", f"#define R3MONO_H {CH}", f"#define R3MONO_BASE {ASCENT}", f"#define R3MONO_GLYPHS {len(store)}",
         f"#define R3MONO_COUNT {len(cps)}", f"static const unsigned short r3mono_glyph[{len(store)}][{CH}] = {{"]
    for h in store:
        L.append("{" + ",".join(f"0x{r:03x}" for r in rows_of(h)) + "},")
    L.append("};")
    L.append(f"static const unsigned int r3mono_cp[{len(cps)}] = {{")
    for i in range(0, len(cps), 12):
        L.append(",".join(f"0x{c:x}" for c in cps[i:i + 12]) + ",")
    L.append("};")
    L.append(f"static const unsigned short r3mono_idx[{len(cps)}] = {{")
    for i in range(0, len(cps), 16):
        L.append(",".join(str(cmap[c]) for c in cps[i:i + 16]) + ",")
    L += ["};", "", "/* The 10 x 20 bitmap (r3mono_glyph row array) of a code point, or NULL. */",
          "static inline const unsigned short *r3mono_find(unsigned int cp) {",
          f"    int lo = 0, hi = {len(cps)} - 1;", "    while (lo <= hi) {", "        int mid = (lo + hi) / 2;",
          "        if (r3mono_cp[mid] == cp) return r3mono_glyph[r3mono_idx[mid]];",
          "        if (r3mono_cp[mid] < cp) lo = mid + 1; else hi = mid - 1;", "    }", "    return 0;", "}", "", "#endif", ""]
    return "\n".join(L)


def lua_table(R, store, cmap):
    cps = sorted(cmap)
    L = ["-- " + HEAD.replace("\n", "\n-- "),
         "-- glyphs[i]: 20 rows of 3 hex digits (10 bits, the top bit the leftmost pixel), row 0 the top. cmap[code point] = i (1-based).",
         f"-- Capitals are rows 3-14 (0-based), the baseline is below row {ASCENT - 1}.", "return {", f"  width = {CW}, height = {CH}, base = {ASCENT},", "  glyphs = {"]
    for h in store:
        L.append('    "' + "".join(f"{r:03x}" for r in rows_of(h)) + '",')
    L += ["  },", "  cmap = {"]
    for i in range(0, len(cps), 6):
        L.append("    " + " ".join(f"[{c}]={cmap[c] + 1}," for c in cps[i:i + 6]))
    L += ["  },", "}", ""]
    return "\n".join(L)


def names_lua(R):
    L = ["-- " + HEAD.replace("\n", "\n-- "), "-- names[name] = the UTF-8 string to print (one code point, or two for a 20x20 icon: left cell then right).", "return {"]
    for n in sorted(R.names):
        esc = "".join("".join("\\%03d" % b for b in chr(c).encode("utf-8")) for c in R.names[n])
        L.append(f'  ["{n}"] = "{esc}",')
    L += ["}", ""]
    return "\n".join(L)


def names_h(R):
    L = ["/* " + HEAD.replace("\n", "\n * ") + "\n * One UTF-8 string a name (octal escapes, so a following digit cannot join them); a two-cell icon is both cells.\n"
         " * R3I_<NAME> macros for names known when you write the code, r3mono_name(\"pad.btn.A.on\") for names built at run time. */",
         "#ifndef R3I6NOS_MONO_NAMES_H", "#define R3I6NOS_MONO_NAMES_H", "#include <string.h>"]
    for n in sorted(R.names):
        L.append(f'#define {c_name(n)} "' + "".join(utf8_oct(c) for c in R.names[n]) + '"')
    L += ["typedef struct { const char *name, *utf8; } R3MonoName;", "static const R3MonoName r3mono_names[] = {"]
    for n in sorted(R.names):
        L.append(f'    {{"{n}", {c_name(n)}}},')
    L += ["};", "/* The string for a glyph name (sorted table, binary search), or NULL. */",
          "static inline const char *r3mono_name(const char *name) {",
          "    int lo = 0, hi = (int)(sizeof r3mono_names / sizeof r3mono_names[0]) - 1;",
          "    while (lo <= hi) {", "        int mid = (lo + hi) / 2, c = strcmp(name, r3mono_names[mid].name);",
          "        if (c == 0) return r3mono_names[mid].utf8;", "        if (c < 0) hi = mid - 1; else lo = mid + 1;", "    }",
          "    return 0;", "}", "#endif", ""]
    return "\n".join(L)


def json_table(R, store, cmap):
    d = {"family": FAMILY, "width": CW, "height": CH, "base": ASCENT, "glyphs": ["".join(f"{r:03x}" for r in rows_of(h)) for h in store],
         "cmap": {str(c): cmap[c] for c in sorted(cmap)}, "names": {n: R.names[n] for n in sorted(R.names)}}
    return json.dumps(d, separators=(",", ":")) + "\n"


